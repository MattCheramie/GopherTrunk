func TestDescrambleInvertRoundTrip(t *testing.T) {
	t.Parallel()
	pcm := []byte{0x10, 0x00, 0x20, 0x00, 0x30, 0x00, 0x40, 0x00}
	in := writeFile(t, "s.s16", pcm)
	outDir := t.TempDir()
	out1 := filepath.Join(outDir, "i1.s16")
	runMode(t, "descramble", "invert", []string{"-in", in, "-out", out1})
	out2 := filepath.Join(outDir, "i2.s16")
	runMode(t, "descramble", "invert", []string{"-in", out1, "-out", out2})
	got, err := os.ReadFile(out2)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, pcm) {
		t.Fatalf("double invert != original: %v vs %v", got, pcm)
	}
}

// --- tiny local CRC-16/GSM + hex helpers, independent of the engine, so the
// test's expected values aren't generated by the code under test. ---

func crc16gsm(data []byte) uint64 {
	crc := uint16(0)
	for _, b := range data {
		crc ^= uint16(b) << 8
		for i := 0; i < 8; i++ {
			if crc&0x8000 != 0 {
				crc = (crc << 1) ^ 0x1021
			} else {
				crc <<= 1
			}
		}
	}
	return uint64(crc ^ 0xFFFF)
}

func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b := make([]byte, len(s)/2)
	for i := 0; i < len(b); i++ {
		var v int
		_, err := fscan(s[2*i:2*i+2], &v)
		if err != nil {
			t.Fatal(err)
		}
		b[i] = byte(v)
	}
	return b
}

func fscan(s string, v *int) (int, error) {
	n := 0
	for _, c := range s {
		n *= 16
		switch {
		case c >= '0' && c <= '9':
			n += int(c - '0')
		case c >= 'a' && c <= 'f':
			n += int(c-'a') + 10
		case c >= 'A' && c <= 'F':
			n += int(c-'A') + 10
		}
	}
	*v = n
	return 1, nil
}

func itoaHex(v uint64) string {
	const digits = "0123456789abcdef"
	if v == 0 {
		return "0"
	}
	var buf []byte
	for v > 0 {
		buf = append([]byte{digits[v&0xf]}, buf...)
		v >>= 4
	}
	return string(buf)
}
