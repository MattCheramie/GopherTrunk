func writeFile(t *testing.T, name string, data []byte) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(p, data, 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func runMode(t *testing.T, toolName, modeName string, args []string) *cryptolab.Result {
	t.Helper()
	_, mode, err := cryptolab.LookupMode(toolName, modeName)
	if err != nil {
		t.Fatalf("lookup %s/%s: %v", toolName, modeName, err)
	}
	env := cryptolab.Env{Stdout: &bytes.Buffer{}, Format: cryptolab.FormatText}
	res, err := mode.Run(context.Background(), args, env)
	if err != nil {
		t.Fatalf("%s/%s run: %v", toolName, modeName, err)
	}
	return res
}

func TestAllGenericToolsRegistered(t *testing.T) {
	t.Parallel()
	for _, name := range []string{"stats", "brute", "lfsr", "crc", "descramble"} {
		if _, ok := cryptolab.Lookup(name); !ok {
			t.Fatalf("tool %q not registered", name)
		}
	}
}

func TestStatsScan(t *testing.T) {
	t.Parallel()
	in := writeFile(t, "p.bin", []byte("the quick brown fox jumps over the lazy dog again and again"))
	res := runMode(t, "stats", "scan", []string{"-in", in})
	if res.Tool != "stats" || len(res.Fields) == 0 {
		t.Fatalf("unexpected result %+v", res)
	}
}

func TestBruteXORRecovers(t *testing.T) {
	t.Parallel()
	pt := []byte("CALL UNIT 12 ON CHANNEL 7 FOR THE DISPATCH BRIDGE NOW PLEASE OK")
	ct := make([]byte, len(pt))
	for i := range pt {
		ct[i] = pt[i] ^ 0x6B
	}
	in := writeFile(t, "c.bin", ct)
	res := runMode(t, "brute", "xor", []string{"-in", in})
	if len(res.Findings) == 0 {
		t.Fatal("no findings")
	}
}

func TestCRCRecoverTool(t *testing.T) {
	t.Parallel()
	// Build frames.txt (datahex,crchex) with CRC-16/GSM computed by a local
	// helper, so the expected values aren't produced by the code under test.
	lines := ""
	for _, d := range []string{"52414449", "554e49542d3037", "44495350"} {
		data := mustHex(t, d)
		c := crc16gsm(data)
		lines += d + "," + itoaHex(c) + "\n"
	}
	in := writeFile(t, "frames.txt", []byte(lines))
	res := runMode(t, "crc", "recover", []string{"-in", in, "-widths", "16"})
	if len(res.Findings) == 0 {
		t.Fatalf("no CRC candidates recovered: %+v", res)
	}
}

